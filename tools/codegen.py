"""Generates the Rust data modules from the pinned pdfminer.six and the reference Python.

Data tables are not ported by hand: they are read from the Python modules themselves (so they
are exactly what pdfminer uses) and written as Rust. Run after every upstream update:

    uv run python tools/codegen.py

Outputs (all marked @generated, never edit them by hand):
    crates/pdfminer/src/glyphlist.rs       <- pdfminer.glyphlist.glyphname2unicode
    crates/pdfminer/src/latin_enc.rs       <- pdfminer.latin_enc.ENCODING
    crates/pdfminer/src/fontmetrics.rs     <- pdfminer.fontmetrics.FONT_METRICS
    crates/pdfminer/src/pyrt/unicode_tables.rs <- this Python's str.isspace / str.isprintable
"""

import sys
from pathlib import Path

from pdfminer import __version__
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode
from pdfminer.latin_enc import ENCODING

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "crates" / "pdfminer" / "src"


def header(source: str) -> str:
    return (
        f"//! @generated by tools/codegen.py from {source} "
        f"(pdfminer.six {__version__}, Python {sys.version.split()[0]}). Do not edit.\n\n"
    )


def rust_str(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:x}}}")
    return '"' + "".join(out) + '"'


def rust_f64(x: float) -> str:
    # repr is the shortest string that round-trips, and Rust parses literals with correct
    # rounding too, so the value is bit-identical.
    r = repr(x)
    if "e" not in r and "." not in r and "inf" not in r and "nan" not in r:
        r += ".0"
    assert float(r) == x
    return f"{r}_f64"


def write(path: Path, text: str) -> None:
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")


def gen_glyphlist() -> None:
    items = sorted(glyphname2unicode.items())
    for _, v in items:
        assert not any(0xD800 <= ord(c) <= 0xDFFF for c in v)
    lines = [header("pdfminer/glyphlist.py")]
    lines.append("/// `glyphname2unicode`, sorted by glyph name (look up with [`glyphname2unicode`]).\n")
    lines.append("pub static GLYPHNAME2UNICODE: &[(&str, &str)] = &[\n")
    for k, v in items:
        lines.append(f"    ({rust_str(k)}, {rust_str(v)}),\n")
    lines.append("];\n\n")
    lines.append(
        "/// `glyphname2unicode[name]`, or `None` for a missing key.\n"
        "pub fn glyphname2unicode(name: &str) -> Option<&'static str> {\n"
        "    GLYPHNAME2UNICODE\n"
        "        .binary_search_by(|(k, _)| (*k).cmp(name))\n"
        "        .ok()\n"
        "        .map(|i| GLYPHNAME2UNICODE[i].1)\n"
        "}\n"
    )
    write(SRC / "glyphlist.rs", "".join(lines))


def gen_latin_enc() -> None:
    def opt(x: int | None) -> str:
        return "None" if x is None else f"Some({x})"

    lines = [header("pdfminer/latin_enc.py")]
    lines.append("/// One row of `ENCODING`: (name, std, mac, win, pdf).\n")
    lines.append(
        "pub type EncodingRow = (&'static str, Option<u8>, Option<u8>, Option<u8>, Option<u8>);\n\n"
    )
    lines.append("/// `ENCODING`, in the upstream order.\n")
    lines.append("pub static ENCODING: &[EncodingRow] = &[\n")
    for name, std, mac, win, pdf in ENCODING:
        lines.append(
            f"    ({rust_str(name)}, {opt(std)}, {opt(mac)}, {opt(win)}, {opt(pdf)}),\n"
        )
    lines.append("];\n")
    write(SRC / "latin_enc.rs", "".join(lines))


def gen_fontmetrics() -> None:
    # Fonts that share their tables (FONT_METRICS["Arial"] = FONT_METRICS["Helvetica"]) are
    # written once and referenced by name, keeping the dict's insertion order.
    first_name: dict[int, str] = {}
    lines = [header("pdfminer/fontmetrics.py")]
    lines.append(
        "/// A value of a font's properties dict, with the Python type it has upstream.\n"
        "#[derive(Clone, Copy, Debug, PartialEq)]\n"
        "pub enum FontMetricValue {\n"
        "    Str(&'static str),\n"
        "    Int(i64),\n"
        "    Float(f64),\n"
        "    /// A tuple of floats (`FontBBox`).\n"
        "    FloatTuple(&'static [f64]),\n"
        "}\n\n"
        "/// `(props, widths)` of one font: the properties dict in insertion order and the\n"
        "/// glyph-name -> width dict in insertion order.\n"
        "pub type FontMetrics = (&'static [(&'static str, FontMetricValue)], &'static [(&'static str, i64)]);\n\n"
    )
    entries = []
    for name, (props, widths) in FONT_METRICS.items():
        key = id(props)
        if key in first_name:
            entries.append((name, first_name[key]))
            continue
        first_name[key] = name
        ident = "FM_" + "".join(c if c.isalnum() else "_" for c in name).upper()
        prop_items = []
        for k, v in props.items():
            if isinstance(v, str):
                pv = f"FontMetricValue::Str({rust_str(v)})"
            elif isinstance(v, bool):
                raise TypeError(v)
            elif isinstance(v, int):
                pv = f"FontMetricValue::Int({v})"
            elif isinstance(v, float):
                pv = f"FontMetricValue::Float({rust_f64(v)})"
            elif isinstance(v, tuple):
                assert all(isinstance(e, float) for e in v), v
                pv = "FontMetricValue::FloatTuple(&[" + ", ".join(rust_f64(e) for e in v) + "])"
            else:
                raise TypeError(v)
            prop_items.append(f"({rust_str(k)}, {pv})")
        width_items = []
        for k, v in widths.items():
            assert isinstance(k, str) and isinstance(v, int) and not isinstance(v, bool)
            width_items.append(f"({rust_str(k)}, {v})")
        lines.append(f"static {ident}: FontMetrics = (\n    &[\n")
        for p in prop_items:
            lines.append(f"        {p},\n")
        lines.append("    ],\n    &[\n")
        for w in width_items:
            lines.append(f"        {w},\n")
        lines.append("    ],\n);\n\n")
        entries.append((name, ident))
    idents = {n: i for n, i in entries if i.startswith("FM_")}
    lines.append("/// `FONT_METRICS`, in the dict's insertion order.\n")
    lines.append("pub static FONT_METRICS: &[(&str, &FontMetrics)] = &[\n")
    for name, target in entries:
        ident = target if target.startswith("FM_") else idents[target]
        lines.append(f"    ({rust_str(name)}, &{ident}),\n")
    lines.append("];\n\n")
    lines.append(
        "/// `FONT_METRICS[name]`, or `None` for a missing key.\n"
        "pub fn font_metrics(name: &str) -> Option<&'static FontMetrics> {\n"
        "    FONT_METRICS.iter().find(|(k, _)| *k == name).map(|(_, m)| *m)\n"
        "}\n"
    )
    write(SRC / "fontmetrics.rs", "".join(lines))


def ranges(pred) -> list[tuple[int, int]]:
    out = []
    start = None
    for c in range(0x110000):
        p = pred(c)
        if p and start is None:
            start = c
        elif not p and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def gen_unicode_tables() -> None:
    spaces = [c for c in range(0x80, 0x110000) if chr(c).isspace()]
    nonprintable = ranges(lambda c: not chr(c).isprintable())
    lines = [header(f"Python {sys.version.split()[0]} str methods")]
    lines.append("/// Code points >= 0x80 for which `str.isspace()` is true.\n")
    lines.append(
        "pub static SPACE_CODE_POINTS: &[u32] = &["
        + ", ".join(f"0x{c:X}" for c in spaces)
        + "];\n\n"
    )
    lines.append("/// Inclusive ranges of code points for which `str.isprintable()` is false.\n")
    lines.append("pub static NONPRINTABLE_RANGES: &[(u32, u32)] = &[\n")
    for lo, hi in nonprintable:
        lines.append(f"    (0x{lo:X}, 0x{hi:X}),\n")
    lines.append("];\n")
    write(SRC / "pyrt" / "unicode_tables.rs", "".join(lines))


if __name__ == "__main__":
    gen_glyphlist()
    gen_latin_enc()
    gen_fontmetrics()
    gen_unicode_tables()
