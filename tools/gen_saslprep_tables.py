"""Generates the Unicode 3.2.0 tables of crates/pdfminer/src/_saslprep.rs.

pdfminer's `_saslprep.py` uses `stringprep` (RFC 3454 tables over `unicodedata.ucd_3_2_0`) and
`unicodedata.ucd_3_2_0.normalize("NFKC", ...)`. This script writes the 3.2.0 properties those
need (general category, bidirectional class, CPython's normalization corrections) between the
`BEGIN GENERATED` / `END GENERATED` markers of `_saslprep.rs`.

    uv run python tools/gen_saslprep_tables.py
"""

import pathlib
import sys
import unicodedata

ucd = unicodedata.ucd_3_2_0
TARGET = pathlib.Path(__file__).resolve().parent.parent / "crates/pdfminer/src/_saslprep.rs"


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs, doc):
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    row = []
    for a, b in rs:
        row.append(f"(0x{a:04X}, 0x{b:04X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def corrections():
    # CPython's `normalization_3_2_0(code)`: characters whose decomposition was corrected after
    # 3.2.0; the 3.2.0 database decomposes them to their original (single) mapping.
    out = []
    for cp in range(0x110000):
        c = chr(cp)
        if 0xD800 <= cp < 0xE000 or ucd.category(c) == "Cn":
            continue
        old = ucd.normalize("NFD", c)
        new = unicodedata.normalize("NFD", c)
        if old != new:
            assert len(old) == 1, (hex(cp), old)
            out.append((cp, ord(old)))
    return out


def main():
    parts = [
        emit("UNASSIGNED", ranges(lambda c: ucd.category(c) == "Cn"), "General category `Cn` in 3.2.0."),
        emit("CAT_ZS", ranges(lambda c: ucd.category(c) == "Zs"), "General category `Zs` in 3.2.0."),
        emit("CAT_CC", ranges(lambda c: ucd.category(c) == "Cc"), "General category `Cc` in 3.2.0."),
        emit("CAT_CO", ranges(lambda c: ucd.category(c) == "Co"), "General category `Co` in 3.2.0."),
        emit(
            "BIDI_R_AL",
            ranges(lambda c: ucd.bidirectional(c) in ("R", "AL")),
            "Bidirectional class `R` or `AL` in 3.2.0 (table D.1).",
        ),
        emit("BIDI_L", ranges(lambda c: ucd.bidirectional(c) == "L"), "Bidirectional class `L` in 3.2.0 (table D.2)."),
    ]
    corr = corrections()
    parts.append(
        "/// CPython's `normalization_3_2_0`: `(code, original mapping)`.\n"
        "pub(crate) const NORMALIZATION_CORRECTIONS: &[(u32, u32)] = &[\n"
        + "".join(f"    (0x{a:04X}, 0x{b:04X}),\n" for a, b in corr)
        + "];"
    )
    body = "\n\n".join(parts)
    src = TARGET.read_text()
    begin = "// BEGIN GENERATED by tools/gen_saslprep_tables.py (do not edit)\n"
    end = "// END GENERATED\n"
    i, j = src.index(begin), src.index(end)
    TARGET.write_text(src[: i + len(begin)] + body + "\n" + src[j:])
    print(f"wrote {TARGET}", file=sys.stderr)


if __name__ == "__main__":
    main()
